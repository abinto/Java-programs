public class VisitorPass {

    public static void main(String[] args) {

        // Stores the visitor's name
        String visitorName = "Abinto";

        // Stores the date of the visit
        String visitDate = "17-08-2026";

        // Stores the name of the employee being visited
        String hostEmployee = "Rahul";

        // Stores the unique pass number
        int passNumber = 101;

        System.out.println("\n\t===== VISITOR PASS =====");
        System.out.println("\tPass Number : " + passNumber);
        System.out.println("\tVisitor     : " + visitorName);
        System.out.println("\tVisit Date  : " + visitDate);
        System.out.println("\tHost        : " + hostEmployee);
        System.out.println("\t========================");
    }
}